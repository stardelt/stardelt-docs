#!/usr/bin/env node
// Generate docs/reference/ from the committed snapshots in reference-src/.
//
// The output is deterministic: the same snapshots always produce the same
// bytes, so CI can regenerate the pages and fail when they differ from the
// committed ones. Never edit docs/reference/ by hand.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'reference-src');
const schemaDir = join(srcDir, 'schemas');
const exampleDir = join(srcDir, 'examples');
const outDir = join(root, 'docs', 'reference');
const resourceDir = join(outDir, 'resources');

const HEADER =
  '<!-- Generated by scripts/gen-reference.mjs from reference-src/. Do not edit. -->';
const MAX_DEPTH = 4;
const METHOD_ORDER = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'];

const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * Remove references to internal design material from prose that came out of
 * a source repository. The snapshots stay byte copies; only the public page
 * is cleaned.
 */
function publicText(value) {
  if (typeof value !== 'string') return '';
  return value
    .replace(
      /\s*\((?:decisions? D\d+[^)]*|D\d+[^)]*|master spec[^)]*|internal note[^)]*)\)/gi,
      '',
    )
    .replace(/\s+/g, ' ')
    .trim();
}

/** Prose cleanup on top of publicText: a removed parenthetical leaves "word ." behind. */
function proseText(value) {
  return publicText(value).replace(/\s+([.,;:])(?!\.)/g, '$1');
}

/** Escape characters that MDX would otherwise read as JSX, but leave code spans alone. */
function mdText(value) {
  return String(value)
    .split(/(`[^`]*`)/g)
    .map((part, index) =>
      index % 2 === 1 ? part : part.replace(/([<>{}])/g, '\\$1'),
    )
    .join('');
}

function cell(value) {
  return mdText(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function renderTable(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`),
  ].join('\n');
}

function frontMatter(title, sidebarLabel) {
  return [
    '---',
    `title: ${JSON.stringify(title)}`,
    `sidebar_label: ${JSON.stringify(sidebarLabel)}`,
    'generated: true',
    'custom_edit_url: null',
    '---',
  ].join('\n');
}

function page(title, sidebarLabel, body) {
  return `${frontMatter(title, sidebarLabel)}\n\n${HEADER}\n\n${body.trim()}\n`;
}

/** Resolve a local JSON pointer (`#/$defs/X`, `#/components/schemas/X`). */
function makeResolver(document) {
  return (ref) => {
    if (typeof ref !== 'string' || !ref.startsWith('#/')) {
      throw new Error(`unsupported $ref ${JSON.stringify(ref)}`);
    }
    let node = document;
    for (const raw of ref.slice(2).split('/')) {
      const key = decodeURIComponent(raw).replace(/~1/g, '/').replace(/~0/g, '~');
      node = node?.[key];
      if (node === undefined) throw new Error(`unresolved $ref ${ref}`);
    }
    return node;
  };
}

/**
 * Follow $refs and collapse oneOf/anyOf. An enum union stays a string enum;
 * any other union takes its first object-ish branch.
 */
function effective(schema, resolve) {
  if (!schema || typeof schema !== 'object') return {};
  let out = { ...schema };
  if (out.$ref) {
    const target = resolve(out.$ref);
    out = { ...target, ...out };
    delete out.$ref;
  }

  const branches = out.oneOf || out.anyOf;
  if (Array.isArray(branches) && branches.length > 0) {
    const resolved = branches.map((branch) => effective(branch, resolve));
    const enums = resolved.flatMap((branch) => (Array.isArray(branch.enum) ? branch.enum : []));
    const onlyEnums = resolved.every(
      (branch) =>
        Array.isArray(branch.enum) ||
        branch.type === 'null' ||
        (Array.isArray(branch.type) && branch.type.every((type) => type === 'null')),
    );
    if (enums.length > 0 && onlyEnums) {
      out = { ...out, type: 'string', enum: [...new Set(enums)] };
    } else {
      const branch = resolved.find((candidate) => candidate.properties || candidate.items || candidate.enum);
      if (branch) out = { ...branch, ...out };
    }
    delete out.oneOf;
    delete out.anyOf;
  }
  return out;
}

function typeLabel(schema, resolve, depth = 0) {
  if (!schema || typeof schema !== 'object') return 'any';
  let { type } = schema;
  let nullable = schema.nullable === true;
  if (Array.isArray(type)) {
    nullable = nullable || type.includes('null');
    const concrete = type.filter((entry) => entry !== 'null');
    type = concrete.length === 1 ? concrete[0] : concrete.join(' | ');
  }
  if (!type) {
    if (schema.enum) type = 'string';
    else if (schema.properties || schema.additionalProperties) type = 'object';
    else if (schema.items) type = 'array';
    else type = 'any';
  }

  if (type === 'object' && schema.additionalProperties !== undefined) {
    const value = schema.additionalProperties;
    const valueType =
      value === true || value === undefined
        ? 'any'
        : depth >= 3
          ? 'object'
          : typeLabel(effective(value, resolve), resolve, depth + 1);
    type = `object (map of ${valueType})`;
  } else if (type === 'array' && schema.items) {
    const itemType =
      depth >= 3 ? 'object' : typeLabel(effective(schema.items, resolve), resolve, depth + 1);
    type = itemType === 'any' ? 'array' : `array of ${itemType}`;
  }

  return nullable ? `${type} (nullable)` : type;
}

function defaultLabel(schema) {
  if (!Object.prototype.hasOwnProperty.call(schema, 'default')) return '';
  const value = schema.default;
  if (typeof value === 'string') return value === '' ? '`""`' : `\`${value}\``;
  if (value === null) return '`null`';
  if (typeof value === 'object') return `\`${JSON.stringify(value)}\``;
  return `\`${String(value)}\``;
}

function constraints(schema) {
  const parts = [];
  if (Array.isArray(schema.enum)) {
    parts.push(schema.enum.map((value) => `\`${value}\``).join(', '));
  }
  const min =
    schema.minLength ?? schema.minimum ?? schema.minItems ?? schema.minProperties ?? undefined;
  const max =
    schema.maxLength ?? schema.maximum ?? schema.maxItems ?? schema.maxProperties ?? undefined;
  if (min !== undefined && max !== undefined) parts.push(`min ${min}, max ${max}`);
  else if (min !== undefined) parts.push(`min ${min}`);
  else if (max !== undefined) parts.push(`max ${max}`);
  if (schema.pattern) parts.push(`pattern \`${schema.pattern}\``);
  if (schema.format) parts.push(`format \`${schema.format}\``);
  return parts.join('; ');
}

function collectRows(node, prefix, depth, resolve) {
  const rows = [];
  const properties = node?.properties;
  if (!properties) return rows;
  const required = new Set(node.required || []);

  for (const name of Object.keys(properties).sort(byName)) {
    const property = effective(properties[name], resolve);
    const path = `${prefix}${name}`;
    rows.push([
      `\`${path}\``,
      typeLabel(property, resolve),
      required.has(name) ? 'Yes' : 'No',
      defaultLabel(property),
      proseText(property.description),
      constraints(property),
    ]);
    if (depth >= MAX_DEPTH) continue;

    if (property.type === 'array' || property.items) {
      const item = effective(property.items || {}, resolve);
      if (item.properties) rows.push(...collectRows(item, `${path}[].`, depth + 1, resolve));
    } else if (property.properties) {
      rows.push(...collectRows(property, `${path}.`, depth + 1, resolve));
    } else if (property.additionalProperties && typeof property.additionalProperties === 'object') {
      const value = effective(property.additionalProperties, resolve);
      if (value.properties) rows.push(...collectRows(value, `${path}{}.`, depth + 1, resolve));
    }
  }
  return rows;
}

function collectValidations(node) {
  const messages = [];
  const visit = (value) => {
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    if (!value || typeof value !== 'object') return;
    if (Array.isArray(value['x-kubernetes-validations'])) {
      for (const validation of value['x-kubernetes-validations']) {
        if (validation && typeof validation.message === 'string') {
          messages.push(validation.message);
        }
      }
    }
    Object.values(value).forEach(visit);
  };
  visit(node);
  return messages;
}

function resourceFileName(kind) {
  return `${kind.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.md`;
}

function renderResource(schema) {
  const kind = schema.title;
  if (typeof kind !== 'string' || kind.length === 0) {
    throw new Error('a schema has no title');
  }
  const resolve = makeResolver(schema);
  const sections = [`# ${mdText(kind)}`];

  const description = proseText(schema.description);
  if (description) sections.push(mdText(description));

  for (const [heading, field] of [
    ['Spec', 'spec'],
    ['Status', 'status'],
  ]) {
    const node = effective(schema.properties?.[field] || {}, resolve);
    const rows = collectRows(node, `${field}.`, 1, resolve);
    sections.push(`## ${heading}`);
    sections.push(rows.length > 0 ? renderTable(
      ['Field', 'Type', 'Required', 'Default', 'Description', 'Constraints'],
      rows,
    ) : '_No fields._');
  }

  const validations = collectValidations(schema);
  if (validations.length > 0) {
    sections.push('## Validation rules');
    sections.push(validations.map((message) => `- ${mdText(publicText(message))}`).join('\n'));
  }

  const base = kind.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  const example = ['.yaml', '.yml']
    .map((extension) => join(exampleDir, `${base}${extension}`))
    .find((file) => existsSync(file));
  if (example) {
    const body = readFileSync(example, 'utf8').trim();
    sections.push('## Example');
    sections.push(`\`\`\`yaml\n${body}\n\`\`\``);
  }

  return page(kind, kind, sections.join('\n\n'));
}

function renderIndex(schemas) {
  const hasScope = schemas.some(
    (schema) => typeof schema['x-kubernetes-scope'] === 'string',
  );
  const rows = schemas
    .slice()
    .sort((a, b) => byName(a.title, b.title))
    .map((schema) => {
      const file = resourceFileName(schema.title);
      const row = [`[${mdText(schema.title)}](./${file})`];
      if (hasScope) row.push(publicText(schema['x-kubernetes-scope']));
      row.push(proseText(schema.description));
      return row;
    });

  const headers = hasScope ? ['Kind', 'Scope', 'Description'] : ['Kind', 'Description'];
  return page(
    'Resources',
    'Resources',
    [
      '# Resources',
      'Every custom resource the operator serves, generated from the JSON Schemas it publishes.',
      renderTable(headers, rows),
    ].join('\n\n'),
  );
}

function pathPrefix(path) {
  const parts = path.split('/').filter(Boolean);
  if (parts[0] === 'api' && parts.length >= 2) return `/api/${parts[1]}`;
  return `/${parts[0] || ''}`;
}

function parameterRows(operation, pathItem, resolve) {
  const merged = new Map();
  for (const parameter of [...(pathItem.parameters || []), ...(operation.parameters || [])]) {
    const resolved = effective(parameter, resolve);
    if (resolved.in !== 'path' && resolved.in !== 'query') continue;
    merged.set(`${resolved.in}:${resolved.name}`, resolved);
  }
  return [...merged.values()]
    .sort((a, b) => byName(a.name, b.name) || byName(a.in, b.in))
    .map((parameter) => [
      `\`${parameter.name}\``,
      parameter.in,
      typeLabel(effective(parameter.schema || {}, resolve), resolve),
      parameter.in === 'path' || parameter.required === true ? 'Yes' : 'No',
      proseText(parameter.description),
    ]);
}

function requestBodyRows(operation, resolve) {
  if (!operation.requestBody) return [];
  const requestBody = effective(operation.requestBody, resolve);
  const content = requestBody.content || {};
  const media = content['application/json'] || Object.values(content)[0];
  if (!media || !media.schema) return [];
  const schema = effective(media.schema, resolve);
  return collectRows(schema, '', 1, resolve);
}

function renderApi(document) {
  const resolve = makeResolver(document);
  const operations = [];
  for (const [path, pathItem] of Object.entries(document.paths || {})) {
    for (const method of METHOD_ORDER) {
      const operation = pathItem[method];
      if (!operation) continue;
      if (!Array.isArray(operation.tags) || !operation.tags.includes('public')) continue;
      operations.push({ path, method, operation, pathItem });
    }
  }
  operations.sort(
    (a, b) =>
      byName(a.path, b.path) ||
      METHOD_ORDER.indexOf(a.method) - METHOD_ORDER.indexOf(b.method),
  );

  const groups = new Map();
  for (const entry of operations) {
    const prefix = pathPrefix(entry.path);
    if (!groups.has(prefix)) groups.set(prefix, []);
    groups.get(prefix).push(entry);
  }

  const sections = [
    '# Nova API',
    'The operations Nova tags `public`: the stable surface for tools and scripts. Generated from `reference-src/nova-openapi.json`.',
    'Every non-2xx answer uses the body shape `{"error": "<sentence>"}`.',
  ];

  for (const prefix of [...groups.keys()].sort(byName)) {
    sections.push(`## ${mdText(prefix)}`);
    for (const { path, method, operation, pathItem } of groups.get(prefix)) {
      sections.push(`### ${method.toUpperCase()} ${mdText(path)}`);

      if (operation.operationId) {
        sections.push(
          `Operation id \`${operation.operationId}\`: in Python \`client.call("${operation.operationId}", …)\`, on the command line \`stardelt api ${operation.operationId}\`.`,
        );
      }

      const summary = proseText(operation.summary);
      const description = proseText(operation.description);
      if (summary && summary !== description) sections.push(mdText(summary));
      if (description) sections.push(mdText(description));

      const parameters = parameterRows(operation, pathItem, resolve);
      if (parameters.length > 0) {
        sections.push('**Parameters**');
        sections.push(renderTable(['Name', 'In', 'Type', 'Required', 'Description'], parameters));
      }

      const bodyRows = requestBodyRows(operation, resolve);
      if (bodyRows.length > 0) {
        sections.push('**Request body**');
        sections.push(
          renderTable(
            ['Field', 'Type', 'Required', 'Default', 'Description', 'Constraints'],
            bodyRows,
          ),
        );
      }

      const responses = Object.entries(operation.responses || {}).sort(([a], [b]) => {
        const left = /^\d+$/.test(a) ? Number(a) : Number.POSITIVE_INFINITY;
        const right = /^\d+$/.test(b) ? Number(b) : Number.POSITIVE_INFINITY;
        return left - right || byName(a, b);
      });
      if (responses.length > 0) {
        sections.push('**Responses**');
        sections.push(
          renderTable(
            ['Code', 'Description'],
            responses.map(([code, response]) => [
              `\`${code}\``,
              proseText(effective(response, resolve).description),
            ]),
          ),
        );
      }
    }
  }

  return page('Nova API', 'Nova API', sections.join('\n\n'));
}

function main() {
  const schemaFiles = readdirSync(schemaDir)
    .filter((name) => name.endsWith('.json'))
    .sort(byName);
  if (schemaFiles.length === 0) {
    throw new Error(`no schemas in ${schemaDir}; run npm run sync:reference first`);
  }

  const schemas = schemaFiles.map((name) =>
    JSON.parse(readFileSync(join(schemaDir, name), 'utf8')),
  );

  const nova = JSON.parse(readFileSync(join(srcDir, 'nova-openapi.json'), 'utf8'));

  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(resourceDir, { recursive: true });

  for (const schema of schemas) {
    writeFileSync(join(resourceDir, resourceFileName(schema.title)), renderResource(schema));
  }
  writeFileSync(join(resourceDir, 'index.md'), renderIndex(schemas));
  writeFileSync(join(outDir, 'api.md'), renderApi(nova));

  console.log(
    `generated ${schemas.length} resource pages, the index and the API page in docs/reference/`,
  );
}

try {
  main();
} catch (error) {
  console.error(`gen-reference: ${error.message}`);
  process.exitCode = 1;
}
